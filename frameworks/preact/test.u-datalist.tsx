// Preact harness page for the shared u-datalist suite (packages/u-datalist/u-datalist.suite.ts).
// Options are rendered from keyed state, the input is a controlled input, and input is bound with onInput
import type {} from "../../packages/u-datalist/dist/u-datalist"; // JSX typings for the u-datalist elements, generated by the build
import "../../packages/u-datalist/u-datalist";
import { log } from "../../packages/harness";
import {
	DEFAULTS,
	datalistAttrs,
	type HarnessConfig,
	inputIds,
	listAttr,
	type Option,
	optionAttrs,
} from "../../packages/u-datalist/u-datalist.harness";
import { type HarnessProps, mountHarness } from "./harness";

function Datalist({ cfg, patch }: HarnessProps<HarnessConfig>) {
	if (!cfg.mounted) return null;
	const list = (id: string, options: Option[]) => (
		<u-datalist {...datalistAttrs(cfg, id)}>
			{options.map((option) => (
				<u-option key={option.key} {...optionAttrs(option)}>
					{option.text}
				</u-option>
			))}
		</u-datalist>
	);

	return (
		<>
			{inputIds(cfg).flatMap((id, index) => [
				<label key={`${id}-label`} for={id}>
					Label {id}
				</label>,
				<input
					key={`${id}-${cfg.inputKey}`}
					id={id}
					list={listAttr(cfg)}
					readOnly={cfg.inputAttrs.readonly !== undefined}
					disabled={cfg.inputAttrs.disabled !== undefined}
					value={index ? undefined : cfg.value}
					onInput={
						index
							? undefined
							: (event) => {
									log("input", event);
									patch({ value: event.currentTarget.value });
								}
					}
				/>,
			])}
			{cfg.options && list(cfg.listId, cfg.options)}
			{cfg.options2 && list(`${cfg.listId}-2`, cfg.options2)}
		</>
	);
}

mountHarness(DEFAULTS, Datalist);
