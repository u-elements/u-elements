// Preact harness page for the shared u-progress suite (packages/u-progress/u-progress.suite.ts).
// value and max are bound as props, which Preact writes as properties on the custom element
import type {} from "../../packages/u-progress/dist/u-progress"; // JSX typings for <u-progress>, generated by the build
import "../../packages/u-progress/u-progress";
import {
	DEFAULTS,
	type HarnessConfig,
	labelId,
	progressAttrs,
} from "../../packages/u-progress/u-progress.harness";
import { type HarnessProps, mountHarness } from "./harness";

function Progress({ cfg }: HarnessProps<HarnessConfig>) {
	if (!cfg.mounted) return null;
	const progress = (
		<u-progress
			{...progressAttrs(cfg)}
			value={cfg.value as number}
			max={cfg.max as number}
			hidden={cfg.hidden}
		/>
	);

	return (
		<>
			{cfg.label === "for" && <label for={cfg.id}>{cfg.text}</label>}
			{cfg.label === "aria-labelledby" && (
				<span id={labelId(cfg)}>{cfg.text}</span>
			)}
			{cfg.label === "wrap" ? (
				// biome-ignore lint/a11y/noLabelWithoutControl: <u-progress> is a polyfill of <progress>
				<label>
					{cfg.text} {progress}
				</label>
			) : (
				progress
			)}
		</>
	);
}

mountHarness(DEFAULTS, Progress);
