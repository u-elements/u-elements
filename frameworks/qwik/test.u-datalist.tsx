// Qwik harness page for the shared u-datalist suite (packages/u-datalist/u-datalist.suite.ts).
// Options are rendered from a keyed store, the input value is bound to the store,
// and input is bound with onInput$, see ./harness.tsx for the dispatch order
import { $, component$, Fragment } from "@qwik.dev/core";
import type {} from "../../packages/u-datalist/dist/u-datalist"; // JSX typings for the u-datalist elements, generated by the build
import "../../packages/u-datalist/u-datalist";
import { log } from "../../packages/harness";
import {
	DEFAULTS,
	datalistAttrs,
	type HarnessConfig,
	inputIds,
	listAttr,
	type Option,
	optionAttrs,
} from "../../packages/u-datalist/u-datalist.harness";
import { type HarnessProps, mountHarness, resolve } from "./harness";

const Datalist = component$(({ cfg }: HarnessProps<HarnessConfig>) => {
	const onInput = $((event: Event, el: HTMLInputElement) => {
		log("input", event);
		cfg.value = el.value;
	});
	resolve(onInput);

	if (!cfg.mounted) return null;
	const list = (id: string, options: Option[]) => (
		<u-datalist {...datalistAttrs(cfg, id)}>
			{options.map((option) => (
				<u-option key={option.key} {...optionAttrs(option)}>
					{option.text}
				</u-option>
			))}
		</u-datalist>
	);

	return (
		<>
			{inputIds(cfg).map((id, index) => (
				<Fragment key={id}>
					<label for={id}>Label {id}</label>
					<input
						key={cfg.inputKey}
						id={id}
						// @ts-expect-error list is missing from Qwik's input typings
						list={listAttr(cfg)}
						readOnly={cfg.inputAttrs.readonly !== undefined}
						disabled={cfg.inputAttrs.disabled !== undefined}
						value={index ? undefined : cfg.value}
						onInput$={index ? undefined : onInput}
					/>
				</Fragment>
			))}
			{cfg.options && list(cfg.listId, cfg.options)}
			{cfg.options2 && list(`${cfg.listId}-2`, cfg.options2)}
		</>
	);
});

mountHarness(DEFAULTS, Datalist);
