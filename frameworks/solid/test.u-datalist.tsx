// Solid harness page for the shared u-datalist suite (packages/u-datalist/u-datalist.suite.ts).
// Options are rendered from a store keyed by their key, the input value is bound to the store,
// and input is bound with onInput, which Solid delegates to the document
import { For, Show } from "solid-js";
import type {} from "../../packages/u-datalist/dist/u-datalist"; // JSX typings for the u-datalist elements, generated by the build
import "../../packages/u-datalist/u-datalist";
import { log } from "../../packages/harness";
import {
	DEFAULTS,
	datalistAttrs,
	type HarnessConfig,
	inputIds,
	listAttr,
	type Option,
	optionAttrs,
} from "../../packages/u-datalist/u-datalist.harness";
import { attrs, type HarnessProps, mountHarness } from "./harness";

// <For> keys by identity, so iterate the keys to reuse elements across updates that carry new objects
const Options = (props: { options: Option[] }) => {
	const option = (key: string) =>
		props.options.find((option) => option.key === key) as Option;
	return (
		<For each={props.options.map((option) => option.key)}>
			{(key) => (
				<u-option {...attrs(optionAttrs(option(key)))}>
					{option(key).text}
				</u-option>
			)}
		</For>
	);
};

function Datalist(props: HarnessProps<HarnessConfig>) {
	return (
		<Show when={props.cfg.mounted}>
			<For each={inputIds(props.cfg)}>
				{(id, index) => (
					<>
						<label for={id}>Label {id}</label>
						<For each={[props.cfg.inputKey]}>
							{/* Re-created when inputKey changes, like key= in React */}
							{() => (
								<input
									id={id}
									list={listAttr(props.cfg)}
									readonly={props.cfg.inputAttrs.readonly !== undefined}
									disabled={props.cfg.inputAttrs.disabled !== undefined}
									value={index() ? undefined : props.cfg.value}
									onInput={(event) => {
										if (index()) return;
										log("input", event);
										props.patch({ value: event.currentTarget.value });
									}}
								/>
							)}
						</For>
					</>
				)}
			</For>
			<Show when={props.cfg.options}>
				{(options) => (
					<u-datalist {...attrs(datalistAttrs(props.cfg))}>
						<Options options={options()} />
					</u-datalist>
				)}
			</Show>
			<Show when={props.cfg.options2}>
				{(options) => (
					<u-datalist
						{...attrs(datalistAttrs(props.cfg, `${props.cfg.listId}-2`))}
					>
						<Options options={options()} />
					</u-datalist>
				)}
			</Show>
		</Show>
	);
}

mountHarness(DEFAULTS, Datalist);
