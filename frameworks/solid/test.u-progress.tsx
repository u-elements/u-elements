// Solid harness page for the shared u-progress suite (packages/u-progress/u-progress.suite.ts).
// value and max are bound as props, which Solid writes as properties on the custom element
import { Show } from "solid-js";
import type {} from "../../packages/u-progress/dist/u-progress"; // JSX typings for <u-progress>, generated by the build
import "../../packages/u-progress/u-progress";
import {
	DEFAULTS,
	type HarnessConfig,
	labelId,
	progressAttrs,
} from "../../packages/u-progress/u-progress.harness";
import { attrs, type HarnessProps, mountHarness } from "./harness";

function Progress(props: HarnessProps<HarnessConfig>) {
	const progress = () => (
		<u-progress
			{...attrs(progressAttrs(props.cfg))}
			value={props.cfg.value as number}
			max={props.cfg.max as number}
			hidden={props.cfg.hidden}
		/>
	);

	return (
		<Show when={props.cfg.mounted}>
			<Show when={props.cfg.label === "for"}>
				<label for={props.cfg.id}>{props.cfg.text}</label>
			</Show>
			<Show when={props.cfg.label === "aria-labelledby"}>
				<span id={labelId(props.cfg)}>{props.cfg.text}</span>
			</Show>
			<Show when={props.cfg.label === "wrap"} fallback={progress()}>
				{/* biome-ignore lint/a11y/noLabelWithoutControl: <u-progress> is a polyfill of <progress> */}
				<label>
					{props.cfg.text} {progress()}
				</label>
			</Show>
		</Show>
	);
}

mountHarness(DEFAULTS, Progress);
